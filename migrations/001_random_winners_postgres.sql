-- Additive PostgreSQL migration for random winner draws.
-- Existing participant rows are retained. This adds a nullable counter field
-- and new draw tables that reference, but do not replace, participants.
BEGIN;

ALTER TABLE participants
    ADD COLUMN IF NOT EXISTS counter_number VARCHAR(32);

CREATE INDEX IF NOT EXISTS participants_counter_number_idx
    ON participants (counter_number);

CREATE TABLE IF NOT EXISTS draws (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draw_type VARCHAR(16) NOT NULL CHECK (draw_type IN ('random', 'manual')),
    winner_count INTEGER NOT NULL CHECK (winner_count BETWEEN 1 AND 500),
    status VARCHAR(16) NOT NULL DEFAULT 'completed' CHECK (status = 'completed'),
    request_key UUID NOT NULL UNIQUE,
    created_by VARCHAR(120),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

DO $migration$
DECLARE
    participant_id_type TEXT;
BEGIN
    SELECT format_type(a.atttypid, a.atttypmod)
      INTO participant_id_type
      FROM pg_attribute AS a
     WHERE a.attrelid = 'participants'::regclass
       AND a.attname = 'id'
       AND NOT a.attisdropped;

    IF participant_id_type IS NULL THEN
        RAISE EXCEPTION 'Expected participants.id column was not found';
    END IF;

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS draw_winners (
            draw_id BIGINT NOT NULL REFERENCES draws(id) ON DELETE CASCADE,
            participant_id %s NOT NULL REFERENCES participants(id) ON DELETE RESTRICT,
            position INTEGER NOT NULL CHECK (position BETWEEN 1 AND 500),
            PRIMARY KEY (draw_id, participant_id),
            UNIQUE (draw_id, position)
        )',
        participant_id_type
    );
END
$migration$;

COMMIT;
